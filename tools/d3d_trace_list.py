#!/usr/bin/env python3
"""Writes app/src/sf4_d3d_trace_all.inc: one X(address) per recompiled function of the game's Direct3D.

The range is the XDK Direct3D library statically linked into default.xex, found with tools/import_map.py (the Vd*,
Mm*Physical* and KeGetCurrentProcessType users sit in 0x8220E000-0x8222BFFF) and the call graph (the functions of
0x8220C000-0x8220DFFF are called from that core). A second cluster, 0x82287000-0x8228B7FF, calls into the core and
holds the draw functions that build DRAW_INDX packets (tools/pm4_scan.py) and the caller of the swap: it is listed
too. src/sf4_d3d_trace.cpp wraps every function of the list; its kRanges must match these ranges.

The file name ends in _all.inc on purpose: tools/direct_calls.py does not read such files, so the list does not
stop the Switch build from making these calls direct (the trace is a PC diagnostic).

    python tools/callgraph.py build
    python tools/d3d_trace_list.py [--range 0x8220C000-0x8222C000 --range 0x82287000-0x8228B800]
"""
import argparse
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--range", action="append", default=[], help="lo-hi in hex, end excluded")
    p.add_argument("--out", default=os.path.join(ROOT, "app", "src", "sf4_d3d_trace_all.inc"))
    # Functions hooked elsewhere in the app: a second strong definition would not link. src/sf4_commands.cpp hooks
    # the command player 0x82287DF0 (the trace's command sampler is an observer of that hook), the four draw
    # functions the draw opcodes call (the frame decoder checks their arguments) and the once-per-frame present
    # 0x822887A0 (sf4_draw_every_n_frames counts frames with it).
    p.add_argument("--exclude", action="append",
                   default=["0x82287DF0", "0x8228B258", "0x8228B648", "0x8228A8D0", "0x8228AD68", "0x822887A0"])
    a = p.parse_args()
    excluded = {int(x, 16) for x in a.exclude}
    ranges = [tuple(int(x, 16) for x in r.split("-")) for r in (a.range or ["0x8220C000-0x8222C000",
                                                                           "0x82287000-0x8228B800"])]
    funcs = json.load(open(os.path.join(ROOT, "out", "callgraph.json")))
    addrs = sorted(int(m.group(1), 16) for n in funcs for m in [re.match(r"sub_([0-9A-F]{8})$", n)]
                   if m and any(lo <= int(m.group(1), 16) < hi for lo, hi in ranges)
                   and int(m.group(1), 16) not in excluded)
    with open(a.out, "w", newline="\n") as f:
        f.write(f"// Generated by tools/d3d_trace_list.py: the {len(addrs)} recompiled functions of the game's Direct3D\n")
        f.write("// (" + ", ".join(f"0x{lo:08X}-0x{hi - 1:08X}" for lo, hi in ranges) + "). Do not edit; regenerate\n")
        f.write("// after a codegen that changes the ranges.\n")
        for x in addrs:
            f.write(f"X({x:08X})\n")
    print(f"{len(addrs)} functions -> {a.out}")


if __name__ == "__main__":
    main()
